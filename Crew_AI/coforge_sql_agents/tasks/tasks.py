from crewai import Task
from agents.sql_executor_agent import sql_executor
from agents.sql_generator import sql_generator
from agents.sql_validator import sql_validator
 
def create_tasks(question):
 
    # TASK 1: SQL GENERATOR
    generate_task = Task(
        description=f"""
        Convert the following user question into a MySQL SELECT query:
 
        User Question:
        {question}
 
        Database Information:
        Database Name: coforge_ai_db
        Table Name: employees
 
        Available Columns:
        employee_id
        employee_name
        department
        salary
        city
 
        STRICT SQL GENERATION RULES:
 
        1. Generate only SELECT queries.
        2. Use only the employees table.
        3. Always use FROM employees.
        4. NEVER use FROM coforge_ai_db.employees.
        5. NEVER include database-qualified table names.
        6. The database is already selected in the MySQL connection.
        7. Do not generate JOIN queries.
        8. Do not generate subqueries or CTEs.
        9. Use only COUNT, SUM, AVG, MIN, MAX
           when aggregate functions are needed.
        10. Use only the available columns.
        11. Do not generate INSERT, UPDATE, DELETE,
            DROP, ALTER or TRUNCATE.
        12. Return only the SQL query.
        13. Do not include Markdown or explanations.
 
        Correct Example:
        SELECT * FROM employees;
 
        Correct Example:
        SELECT employee_name, salary
        FROM employees
        WHERE salary > 50000;
 
        Incorrect Example:
        SELECT * FROM coforge_ai_db.employees;
        """,
        expected_output=(
            "One valid MySQL SELECT query using "
            "unqualified employees table name"
        ),
        agent=sql_generator
    )
 
    # TASK 2: SQL VALIDATOR
    validate_task = Task(
        description="""
        Review the SQL generated by the SQL Generator Agent.
 
        STRICT VALIDATION RULES:
 
        1. The query must be a SELECT query.
        2. Only the employees table is permitted.
        3. All column names must be valid.
        4. The query must answer the user's question.
        5. Database-qualified table names are prohibited.
        6. Reject coforge_ai_db.employees.
        7. Accept FROM employees.
        8. Reject JOIN, subqueries and CTEs.
        9. Reject INSERT, UPDATE, DELETE, DROP,
           ALTER and TRUNCATE.
        10. Reject multiple SQL statements.
        11. Do not add a database prefix to the SQL.
        12. Do not modify the approved SQL unnecessarily.
 
        If the query is valid:
        Return only the approved SQL query.
 
        If the query is invalid:
        Return REJECTED followed by the reason.
 
        Example Approved Output:
        SELECT * FROM employees;
 
        Example Rejected Output:
        REJECTED: Qualified table names are not allowed.
        """,
        expected_output="Approved SQL query or REJECTED with reason",
        agent=sql_validator,
        context=[generate_task]
    )
 
    # TASK 3: SQL EXECUTOR
    execute_task = Task(
        description="""
        Execute the approved SQL query from the SQL Validator.
 
        EXECUTION RULES:
 
        1. Read the SQL Validator's output.
        2. If the output starts with REJECTED,
           do not execute the query.
        3. Otherwise, call the execute_employee_sql tool.
        4. Pass the approved SQL query exactly as received.
        5. Do not add coforge_ai_db to the table name.
        6. Do not generate a new SQL query.
        7. Do not execute INSERT, UPDATE, DELETE or DROP.
        8. Do not invent employee records.
        9. Use only the actual rows returned by the tool.
        10. If the tool reports an error, explain it clearly.
        11. If successful, summarize the database results.
 
        Example Tool Input:
        SELECT * FROM employees;
 
        Expected Behavior:
        Execute SQL against the selected MySQL database
        and return actual employee records.
        """,
        expected_output=(
            "Actual SQL execution results and a clear summary, "
            "or an error explaining why execution failed"
        ),
        agent=sql_executor,
        context=[validate_task]
    )
 
    return [
        generate_task,
        validate_task,
        execute_task
    ]